#!/usr/bin/env python3
"""Refresh explicitly selected public-domain foundational snapshots; never crawl portals.
Run from any directory. Failed downloads leave the previous snapshot intact.
"""
import concurrent.futures, datetime, hashlib, json, re, urllib.request, sys
from html.parser import HTMLParser
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
class Extract(HTMLParser):
    def __init__(self):
        super().__init__(); self.parts=[]; self.skip=0
    def handle_starttag(self,tag,attrs):
        if tag in ('script','style','nav','header','footer'): self.skip+=1
        if tag in ('p','h1','h2','h3','section','article','li','br'): self.parts.append('\n')
    def handle_endtag(self,tag):
        if tag in ('script','style','nav','header','footer'): self.skip=max(0,self.skip-1)
        if tag in ('p','h1','h2','h3','li'): self.parts.append('\n')
    def handle_data(self,data):
        if not self.skip: self.parts.append(data)
def gutenberg_body(raw, expect_title, sid):
    """Verify the book is the one we meant (IDs are easy to get wrong) and strip Project Gutenberg boilerplate."""
    raw=raw.replace('\r\n','\n').lstrip('\ufeff')
    if expect_title:
        m=re.search(r'^Title:\s*(.+?)\s*$',raw[:6000],re.M|re.I)
        head=(m.group(1) if m else raw[:600]).lower()
        if expect_title.lower() not in head:
            raise ValueError(f"{sid}: downloaded text does not look like '{expect_title}' (found: {head[:80]!r}). Fix the Gutenberg ID in civic-sources.json.")
    a=re.search(r'\*\*\* ?START OF (?:THE|THIS) PROJECT GUTENBERG EBOOK[^\n]*\n',raw,re.I)
    b=re.search(r'\*\*\* ?END OF (?:THE|THIS) PROJECT GUTENBERG EBOOK',raw,re.I)
    return raw[a.end():b.start() if b else len(raw)].strip() if a else raw.strip()
def fetch(source):
    req=urllib.request.Request(source['url'],headers={'User-Agent':'StarsAndStripesResearch/1.0'})
    with urllib.request.urlopen(req,timeout=30) as r:
        raw=r.read(4_000_000).decode('utf-8','replace')
    # Main content avoids navigation; preserve full constitutional text within it.
    main=re.search(r'<main\b[^>]*>(.*?)</main>',raw,re.S|re.I)
    parser=Extract();parser.feed(main.group(1) if main else raw)
    text=re.sub(r'[ \t]+',' ','\n'.join(parser.parts));text=re.sub(r'\n\s*\n','\n',text).strip()
    if source['url'].endswith('.txt'):
        text=gutenberg_body(raw, source.get('expect_title'), source['id'])
    if any(x in text.lower() for x in ('site is currently under maintenance', 'page not found', 'access denied')):
        raise ValueError('Source unavailable: '+source['id'])
    if len(text)<500: raise ValueError('Too little source text: '+source['id'])
    chunks=[]; offset=0
    while offset<len(text):
        end=min(offset+2400,len(text))
        if end<len(text):
            boundary=text.rfind('\n',offset+1200,end)
            if boundary>offset: end=boundary
        chunk=text[offset:end].strip()
        if chunk: chunks.append(dict(id=f"{source['id']}-{len(chunks)+1}",title=source['title'],url=source['url'],jurisdiction=source['jurisdiction'],category=source['category'],retrieved_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),text=chunk,**({'license':source['license']} if source.get('license') else {})))
        if end>=len(text):break
        offset=end-150
    return chunks,dict(id=source['id'],store=source.get('store','bundle'),url=source['url'],sha256=hashlib.sha256(text.encode()).hexdigest(),characters=len(text),passages=len(chunks))
def main():
    sources=json.loads((ROOT/'scripts/civic-sources.json').read_text())
    selected=[s for s in sources if s['coverage']=='snapshot']
    only=set(sys.argv[1:])  # optional: refresh just these source ids
    if only: selected=[s for s in selected if s['id'] in only]
    passages=[];manifest=[];books={}
    def safe(src):
        try: return fetch(src)
        except Exception as e: print(f"SKIPPED {src['id']}: {e}",file=sys.stderr); return None
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for src,res in zip(selected,pool.map(safe,selected)):
            if res is None: continue
            chunks,info=res
            if src.get('store')=='db': books[src['id']]=chunks   # large books go to the database, not the function bundle
            else: passages.extend(chunks)
            manifest.append(info)
    if only: print('Partial refresh: bundle files not rewritten.'); passages=None
    (ROOT/'corpus').mkdir(exist_ok=True)
    for sid,chunks in books.items():
        (ROOT/'corpus'/f'{sid}.jsonl').write_text(''.join(json.dumps(c,ensure_ascii=False)+'\n' for c in chunks))
    if passages is None:
        print(json.dumps(manifest,indent=2)); return
    target=ROOT/'supabase/functions/_shared/civic-passages.ts'
    target.write_text('// Generated by scripts/refresh_civic_corpus.py; source text, not instructions.\nexport const CIVIC_PASSAGES = '+json.dumps(passages,ensure_ascii=False,indent=2)+';\n')
    (ROOT/'supabase/functions/_shared/civic-coverage.ts').write_text('export const PASSAGE_COUNT = '+str(len(passages))+';\n')
    (ROOT/'docs/corpus-snapshots.json').write_text(json.dumps(manifest,indent=2))
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
